CREATE TABLE TA_MORADOR (
    id NUMBER(18) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000),
    nome VARCHAR2(120 CHAR) NOT NULL,
    celular VARCHAR2(15 CHAR) NOT NULL,
    bairro VARCHAR2(80 CHAR) NOT NULL,
    CONSTRAINT pk_ta_morador PRIMARY KEY (id),
    CONSTRAINT uk_ta_morador_celular UNIQUE (celular)
);

CREATE TABLE TA_LOJA (
    id NUMBER(18) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000),
    nome VARCHAR2(120 CHAR) NOT NULL,
    endereco VARCHAR2(180 CHAR) NOT NULL,
    horario VARCHAR2(100 CHAR) NOT NULL,
    categoria VARCHAR2(80 CHAR) NOT NULL,
    latitude NUMBER(9,6) NOT NULL,
    longitude NUMBER(9,6) NOT NULL,
    CONSTRAINT pk_ta_loja PRIMARY KEY (id),
    CONSTRAINT ck_ta_loja_lat CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_ta_loja_lon CHECK (longitude BETWEEN -180 AND 180)
);

CREATE TABLE TA_PRODUTO (
    id NUMBER(18) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000),
    nome VARCHAR2(120 CHAR) NOT NULL,
    CONSTRAINT pk_ta_produto PRIMARY KEY (id),
    CONSTRAINT uk_ta_produto_nome UNIQUE (nome)
);

CREATE TABLE TA_ESTOQUE (
    id NUMBER(18) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000),
    loja_id NUMBER(18) NOT NULL,
    produto_id NUMBER(18) NOT NULL,
    quantidade NUMBER(9) NOT NULL,
    preco NUMBER(10,2) NOT NULL,
    atualizado_em TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_ta_estoque PRIMARY KEY (id),
    CONSTRAINT uk_ta_estoque_item UNIQUE (loja_id, produto_id),
    CONSTRAINT ck_ta_estoque_qtd CHECK (quantidade >= 0),
    CONSTRAINT ck_ta_estoque_preco CHECK (preco > 0)
);

CREATE TABLE TA_RESERVA (
    id NUMBER(18) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000),
    morador_id NUMBER(18) NOT NULL,
    estoque_id NUMBER(18) NOT NULL,
    quantidade NUMBER(9) NOT NULL,
    preco_unitario NUMBER(10,2) NOT NULL,
    status VARCHAR2(12 CHAR) DEFAULT 'PENDENTE' NOT NULL,
    criada_em TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_ta_reserva PRIMARY KEY (id),
    CONSTRAINT ck_ta_reserva_qtd CHECK (quantidade > 0),
    CONSTRAINT ck_ta_reserva_preco CHECK (preco_unitario > 0),
    CONSTRAINT ck_ta_reserva_status CHECK (status IN
        ('PENDENTE', 'CONFIRMADA', 'RECUSADA', 'CANCELADA', 'RETIRADA'))
);

ALTER TABLE TA_ESTOQUE ADD CONSTRAINT fk_ta_estoque_loja
    FOREIGN KEY (loja_id) REFERENCES TA_LOJA(id);
ALTER TABLE TA_ESTOQUE ADD CONSTRAINT fk_ta_estoque_produto
    FOREIGN KEY (produto_id) REFERENCES TA_PRODUTO(id);
ALTER TABLE TA_RESERVA ADD CONSTRAINT fk_ta_reserva_morador
    FOREIGN KEY (morador_id) REFERENCES TA_MORADOR(id);
ALTER TABLE TA_RESERVA ADD CONSTRAINT fk_ta_reserva_estoque
    FOREIGN KEY (estoque_id) REFERENCES TA_ESTOQUE(id);
CREATE INDEX ix_ta_estoque_produto ON TA_ESTOQUE(produto_id);
CREATE INDEX ix_ta_reserva_morador ON TA_RESERVA(morador_id);
CREATE INDEX ix_ta_reserva_estoque ON TA_RESERVA(estoque_id, status);
